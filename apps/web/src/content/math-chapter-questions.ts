import type { ContentQuestion, QuestionKind } from "@knowgate/domain";

/**
 * 每章三道题（跟做 / 独立练习 / 章节短测）的手写题库。
 *
 * 之前的版本用里程碑级的种子题循环套模板生成章节题，结果章节里出现了
 * 别章的内容、半截题干和固定答案。这里改为按 chapterId 逐章给出完整题目，
 * 生成器只负责挂到步骤上，不再二次包装题干。
 */

export type ChapterQuestionSeed = Omit<ContentQuestion, "id" | "nodeId">;

export type ChapterQuestionTriple = [
  ChapterQuestionSeed,
  ChapterQuestionSeed,
  ChapterQuestionSeed,
];

function q(
  kind: QuestionKind,
  prompt: string,
  options: string[],
  answerIndex: number,
  explanation: string,
  damage = 1,
): ChapterQuestionSeed {
  return {
    kind,
    prompt,
    options,
    answerIndex,
    explanation,
    timeLimitSec: 45,
    damage,
  };
}

const t = (statement: string, explanation: string): ChapterQuestionSeed =>
  q("judge", statement, ["正确", "错误"], 0, explanation);

